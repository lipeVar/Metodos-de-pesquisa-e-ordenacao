    private void btnExecutarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExecutarActionPerformed
        if(controller.quantidade() == 0) {
            JOptionPane.showMessageDialog(this, "Carregue uma lis de numeros", "Atenção", JOptionPane.ERROR_MESSAGE);
            return;
        }
        String metodo = cmbMetodos.getSelectedItem().toString();
        long inicio = System.currentTimeMillis();
        ArrayList<Float> metricas = controller.execute(metodo);
        long tempo = System.currentTimeMillis() - inicio;
        
        if(metricas.size() < 2){
            JOptionPane.showMessageDialog(this, "Metodo invalido ou fora do padrao suportado", "ERRO", JOptionPane.ERROR_MESSAGE);
            return;
        }
        txtQtdNumeros.setText(String.valueOf(controller.quantidade()));
        txtComparacoes.setText(String.valueOf(metricas.get(0).longValue()));
        txtTroca.setText(String.valueOf(metricas.get(1).longValue()));
        txtTempo.setText(String.valueOf(tempo));
        jPanelMetodos.setVisible(true);
    }//GEN-LAST:event_btnExecutarActionPerformed

    private void btnAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirActionPerformed
        String nomeArquivo = txtAbrirArquivo.getText();
        if(nomeArquivo.equals("")) {
            JOptionPane.showMessageDialog(this, "Informe nome do arquivo", "ERRO", JOptionPane.ERROR_MESSAGE);
            return;    
        }
        if(controller.CarregarArquivo(nomeArquivo)) {
            JOptionPane.showMessageDialog(this, "ListaCarregada com sucesso", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            
        } else{
            JOptionPane.showMessageDialog(this, "Problemas para ler o arquivo e carregar a lista", "ERRO", JOptionPane.ERROR_MESSAGE);
            txtAbrirArquivo.setText("");
        }
        
    }//GEN-LAST:event_btnAbrirActionPerformed

